#!/bin/bash
# Write ~/.omp/agent/zed-models.yml, the overlay that zed/.config/zed/settings.json
# passes to `omp acp --config`. Unscoped, omp's ACP `model` select lists the
# whole catalog (~870); `omp acp --models` does not narrow it, `enabledModels`
# does. Regenerated from modelRoles on every run; re-run after changing roles.
#
# Pitfalls handled (verified against `omp acp` session/new output):
# - Role values are a selector string, comma list, or array. Entries may be
#   `@alias[:level]` (followed), carry a `:thinking` suffix (stripped) or an
#   `@upstream` pin that can contain `/`, e.g. `@google-vertex/global/flex`
#   (stripped: `enabledModels` silently drops pinned ids), or be a
#   bare/partial id (`gpt-6-luna-pr`), emitted as-is for omp's fuzzy match.
# - Full ids become `*/*<id>`: a bare `*` doesn't cross `/`, so `*/` is the
#   provider and the inner `*` an optional vendor folder (openrouter's
#   `anthropic/`). `[.-]` between version digits matches both Anthropic's
#   `5-5` and openrouter's `5.5`.
# - Bedrock (~8 regional copies per Claude model, unconfigured) is disabled;
#   this replaces any global `disabledProviders`.
# - `omp acp --config <missing file>` crashes, so the file is written
#   atomically and must exist before the first Zed omp thread.
set -euo pipefail

config_dir="$(omp config path)"
scope="$config_dir/zed-models.yml"
mkdir -p "$config_dir"

omp config get modelRoles --json | jq -r '
  (.value // {}) as $r
  # A role value: string (possibly comma-separated) or array of strings.
  | def entries($v):
      [$v] | flatten | map(select(type == "string") | split(",")[] | gsub("^\\s+|\\s+$"; "") | select(. != ""));
  # Follow `@alias[:level]` chains; cycles stop at depth 8.
    def resolve($v; $n):
      if $n > 8 then empty
      else entries($v)[]
        | if startswith("@") then resolve($r[.[1:] | sub(":[a-z]+$"; "")]; $n + 1) else . end
      end;
  [ $r | to_entries[] | select(.key != "web") | resolve(.value; 0)
    | select(startswith("web/") | not)
    | sub(":(off|minimal|low|medium|high|xhigh|max|auto)$"; "")
    # Pins start at the first `@` and may contain `/`.
    | sub("@.*$"; "")
    | if test("/") then
        "*/*" + (split("/") | last | gsub("(?<a>[0-9])[.-](?<b>[0-9])"; "\(.a)[.-]\(.b)"))
      else . end ]
  | unique
  | "# Generated by omp/setup-zed-models.sh — do not edit; re-run omp/setup-settings.sh.\n"
    + "disabledProviders:\n  - amazon-bedrock\n  - bedrock-mantle\n"
    + "enabledModels:\n" + (map("  - " + @json) | join("\n")) + "\n"
' >"$scope.tmp"
mv "$scope.tmp" "$scope"
echo "Zed omp model scope: $(grep -c '^  - "' "$scope") patterns in $scope"
